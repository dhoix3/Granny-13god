def deco(kind, x, y, name, container="", hide=None, rot=0, rx=None, ry=None, solid=True):
    d = {"kind": kind, "x": x, "y": y, "name": name, "rot": rot}
    if container:
        d["container"] = container
    if hide:
        d["hide"] = {"label": hide[0], "enter": hide[1], "bed": bool(hide[2]) if len(hide) > 2 else False}
    if rx is not None:
        d["rx"] = rx
    if ry is not None:
        d["ry"] = ry
    d["solid"] = solid
    return d


